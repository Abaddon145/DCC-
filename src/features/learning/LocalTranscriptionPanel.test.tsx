import {act,fireEvent,render,screen,waitFor} from "@testing-library/react";
import {StrictMode} from "react";
import {beforeEach,expect,it,vi} from "vitest";
import {LocalTranscriptionPanel} from "./LocalTranscriptionPanel";
import {learningApi} from "./api";
import {api} from "../../lib/api";
import {open} from "@tauri-apps/plugin-dialog";
import type {WhisperComponentStatus} from "./types";
import type {LibraryTask} from "../../types";
vi.mock("./api",()=>({learningApi:{transcriptionComponents:vi.fn(),importTranscriptionModel:vi.fn(),installTranscriptionTools:vi.fn()}}));
vi.mock("../../lib/api",()=>({api:{startLibraryTask:vi.fn(),listLibraryTasks:vi.fn(),getLibraryTask:vi.fn(),cancelLibraryTask:vi.fn()}}));
vi.mock("@tauri-apps/plugin-dialog",()=>({open:vi.fn()}));
const status:WhisperComponentStatus={version:"1.9.1",modelRevision:"revision",toolReady:true,toolMessage:"已核验",models:[{id:"base",label:"Whisper Base",bytes:147951465,url:"https://example.invalid/base.bin",installed:true,message:"已核验"},{id:"small",label:"Whisper Small",bytes:487601967,url:"https://example.invalid/small.bin",installed:false,message:"模型尚未安装"}]};
const task:LibraryTask={id:"task",libraryId:"lib",label:"本地课程转写",status:"running",phase:"识别中",current:2,total:4,currentName:"课程",createdAt:"now",updatedAt:"now",cancellable:true,message:"",result:null,payload:{kind:"courseTranscription",request:{courseId:"course",modelId:"base"}}};
beforeEach(()=>{vi.clearAllMocks();vi.mocked(learningApi.transcriptionComponents).mockResolvedValue(structuredClone(status));vi.mocked(api.listLibraryTasks).mockResolvedValue([]);vi.mocked(api.startLibraryTask).mockResolvedValue(task);vi.mocked(api.getLibraryTask).mockResolvedValue(task);vi.mocked(api.cancelLibraryTask).mockResolvedValue();});
it("loads in StrictMode without a stale busy lock",async()=>{
  render(<StrictMode><LocalTranscriptionPanel libraryId="lib" courseId="course" onComplete={vi.fn()}/></StrictMode>);
  expect(await screen.findByText(/Whisper 1.9.1/)).toBeInTheDocument();
  expect(screen.getByRole("button",{name:"重新检查组件"})).toBeEnabled();
});
it("requires explicit local consent and submits a typed task with library identity",async()=>{
  render(<LocalTranscriptionPanel libraryId="lib" courseId="course" onComplete={vi.fn()}/>);
  expect(await screen.findByText(/Whisper 1.9.1/)).toBeInTheDocument();
  const start=screen.getByRole("button",{name:"开始本地转写"});expect(start).toBeDisabled();
  fireEvent.click(screen.getByRole("checkbox",{name:/确认使用本机CPU/}));
  fireEvent.click(start);
  await waitFor(()=>expect(api.startLibraryTask).toHaveBeenCalledWith({kind:"courseTranscription",request:{courseId:"course",modelId:"base"}},"lib"));
  expect(await screen.findByRole("button",{name:"取消转写"})).toBeEnabled();
  fireEvent.click(screen.getByRole("button",{name:"取消转写"}));
  await waitFor(()=>expect(api.cancelLibraryTask).toHaveBeenCalledWith("task"));
});
it("does not start without components and imports only an explicitly selected model",async()=>{
  vi.mocked(learningApi.transcriptionComponents).mockResolvedValue({...status,toolReady:false,toolMessage:"缺少组件"});
  vi.mocked(open).mockResolvedValueOnce("C:/chosen/model.bin");
  vi.mocked(learningApi.importTranscriptionModel).mockResolvedValue(status);
  render(<LocalTranscriptionPanel libraryId="lib" courseId="course" onComplete={vi.fn()}/>);
  expect(await screen.findByText("缺少组件")).toBeInTheDocument();
  fireEvent.click(screen.getByRole("checkbox",{name:/确认使用本机CPU/}));
  expect(screen.getByRole("button",{name:"开始本地转写"})).toBeDisabled();
  expect(learningApi.importTranscriptionModel).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole("button",{name:"导入所选模型"}));
  await waitFor(()=>expect(learningApi.importTranscriptionModel).toHaveBeenCalledWith("lib","base","C:/chosen/model.bin"));
  expect(await screen.findByText(/141.1 MiB/)).toBeInTheDocument();
});
it("ignores old-library component responses and refreshes after read errors",async()=>{
  let finish!:(value:WhisperComponentStatus)=>void;
  vi.mocked(learningApi.transcriptionComponents).mockImplementationOnce(()=>new Promise(resolve=>{finish=resolve;}));
  const {rerender}=render(<LocalTranscriptionPanel libraryId="lib" courseId="course" onComplete={vi.fn()}/>);
  await waitFor(()=>expect(finish).toBeDefined());
  vi.mocked(learningApi.transcriptionComponents).mockRejectedValue(new Error("暂时不可读"));
  rerender(<LocalTranscriptionPanel libraryId="new-lib" courseId="new-course" onComplete={vi.fn()}/>);
  expect(await screen.findByRole("alert")).toHaveTextContent("暂时不可读");
  await act(async()=>finish(status));
  expect(screen.queryByText("已核验")).toBeNull();
  vi.mocked(learningApi.transcriptionComponents).mockResolvedValue(status);
  fireEvent.click(screen.getByRole("button",{name:"重新检查组件"}));
  expect(await screen.findByText(/Whisper 1.9.1/)).toBeInTheDocument();
});
it("selects a successfully completed subtitle without triggering paid analysis",async()=>{
  const onComplete=vi.fn();
  vi.mocked(api.startLibraryTask).mockResolvedValue({...task,status:"completed",current:4,result:{courseId:"course",subtitleId:"new-subtitle",cached:false}});
  render(<LocalTranscriptionPanel libraryId="lib" courseId="course" onComplete={onComplete}/>);
  await screen.findByText(/Whisper 1.9.1/);
  fireEvent.click(screen.getByRole("checkbox",{name:/确认使用本机CPU/}));fireEvent.click(screen.getByRole("button",{name:"开始本地转写"}));
  await waitFor(()=>expect(onComplete).toHaveBeenCalledWith("new-subtitle"));
  expect(api.startLibraryTask).toHaveBeenCalledTimes(1);
});
it("does not apply a delayed completion from another library",async()=>{
  let finish!:(value:LibraryTask)=>void;
  vi.mocked(api.startLibraryTask).mockImplementationOnce(()=>new Promise(resolve=>{finish=resolve;}));
  const oldComplete=vi.fn(),newComplete=vi.fn();
  const {rerender}=render(<LocalTranscriptionPanel libraryId="lib" courseId="course" onComplete={oldComplete}/>);
  await screen.findByText(/Whisper 1.9.1/);
  fireEvent.click(screen.getByRole("checkbox",{name:/确认使用本机CPU/}));fireEvent.click(screen.getByRole("button",{name:"开始本地转写"}));
  await waitFor(()=>expect(finish).toBeDefined());
  rerender(<LocalTranscriptionPanel libraryId="other" courseId="another-course" onComplete={newComplete}/>);
  await screen.findByText(/Whisper 1.9.1/);
  await act(async()=>finish({...task,status:"completed",result:{courseId:"course",subtitleId:"old-subtitle"}}));
  expect(oldComplete).not.toHaveBeenCalled();expect(newComplete).not.toHaveBeenCalled();
  expect(screen.queryByRole("button",{name:"载入生成字幕"})).toBeNull();
});
it("installs tools only after explicit package selection and refreshes readiness",async()=>{
  vi.mocked(learningApi.transcriptionComponents).mockResolvedValue({...status,toolReady:false,toolMessage:"缺少组件"});
  vi.mocked(open).mockResolvedValueOnce("C:/chosen/resources");vi.mocked(learningApi.installTranscriptionTools).mockResolvedValue(status);
  render(<LocalTranscriptionPanel libraryId="lib" courseId="course" onComplete={vi.fn()}/>);
  await screen.findByText("缺少组件");
  expect(learningApi.installTranscriptionTools).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole("button",{name:"安装本地组件包"}));
  await waitFor(()=>expect(learningApi.installTranscriptionTools).toHaveBeenCalledWith("lib","C:/chosen/resources"));
  expect(await screen.findByText(/工具已核验/)).toBeInTheDocument();
  expect(screen.getByRole("checkbox",{name:/确认使用本机CPU/})).not.toBeChecked();
});
